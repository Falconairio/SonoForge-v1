function octaveToColor (octave) {
    switch(octave) {
        case 0:
            return "octave0"
        case 1:
            return "octave1"
        case 2:
            return "octave2"
        case 3:
            return "octave3"
        case 4:
            return "octave4"
        case 5:
            return "octave5"
        case 6:
            return "octave6"
        case 7:
            return "octave7"
        case 8:
            return "octave8"
        default:
            return
    }
}

export default octaveToColor